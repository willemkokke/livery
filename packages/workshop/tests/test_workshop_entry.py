    after = _reconcile.installed_distributions(tmp_path)
    assert before["other-2.0.0.dist-info"] == after["other-2.0.0.dist-info"] == ""
    assert before["member-1.0.0.dist-info"] != after["member-1.0.0.dist-info"]


