"""The entry contract and the per-command reconcile.

The emitted ``setup.sh``, the uv pin derived from the lock, the
rendered workflows' bare spelling, and the reconcile that re-syncs a
venv the lock has moved past. Fallbacks before happy paths
throughout: the refusals, the never-fatal failures, and the inert
states are pinned first.
"""

from __future__ import annotations

import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

import pytest

LOCK = """\
version = 1

[[package]]
name = "something"
version = "1.0.0"

[[package]]
name = "uv"
version = "0.12.7"
"""

LOCK_WITHOUT_UV = """\
version = 1

[[package]]
name = "something"
version = "1.0.0"
"""


def _contract_root(tmp_path: Path, kind: str, *, lock: str = LOCK) -> Path:
    root = tmp_path / f"contract-{kind}"
    root.mkdir(exist_ok=True)
    (root / "workshop.toml").write_text(
        "[workspace]\n"
        "extensions = []\n"
        "\n[forge]\n"
        f'kind = "{kind}"\n'
        'owner = "owner"\n'
        "\n[ci]\n"
        'runners = ["ubuntu-latest"]\n'
        'required-context = "gate"\n'
    )
    (root / "pyproject.toml").write_text(
        '[project]\nname = "scratch"\nrequires-python = ">=3.11"\n'
    )
    if lock:
        (root / "uv.lock").write_text(lock)
    return root


