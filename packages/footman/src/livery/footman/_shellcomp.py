def detect_shell() -> str | None:
    """Best-effort, zero-dependency detection of the invoking shell.

    Walks the parent-process tree (the immediate parent is often `uv`, not
    the shell) looking for a known shell name — what shellingham does for
    typer, without the dependency. Windows has no `ps`, so the PowerShell
    tell there is the `PSModulePath` variable it exports to children. Falls
    back to the login shell in `$SHELL`; returns `None` when nothing is
    confidently recognised.
    """
    if os.name == "nt":
        # git-bash (and MSYS2) export MSYSTEM — checked first, because
        # PowerShell's PSModulePath is machine-level environment and is set
        # inside git-bash too. Without this a git-bash user is told "pwsh",
        # which is a small lie that installs the wrong hook.
        if os.environ.get("MSYSTEM"):
            return "bash"
        # PSModulePath still over-claims from cmd.exe — acceptable, because
        # cmd has no completion mechanism and a PowerShell install is the
        # most useful answer on that box. (Real spelling kept; Windows env
        # lookup is case-insensitive anyway.)
        return "pwsh" if os.environ.get("PSModulePath") else None  # noqa: SIM112
    return _detect_posix()


def _detect_posix() -> str | None:
    pid = os.getppid()
    for _ in range(10):
        if pid <= 1:
            break
        try:
            out = subprocess.run(
                ["ps", "-p", str(pid), "-o", "ppid=,comm="],
                capture_output=True,
                text=True,
                timeout=5,
            )
        except (OSError, subprocess.TimeoutExpired):
            break
        line = out.stdout.strip()
        if out.returncode != 0 or not line:
            break
        ppid, _, comm = line.partition(" ")
        # A login shell reports as "-zsh"; comm may be a full path.
        name = Path(comm.strip()).name.lstrip("-")
        if name in _PROC_NAMES:
            return _PROC_NAMES[name]
        try:
            pid = int(ppid)
        except ValueError:
            break
    login = Path(os.environ.get("SHELL", "")).name
    return _PROC_NAMES.get(login)


def _ask_shell(candidates: tuple[str, ...], args: list[str]) -> str | None:
    """Run the first available *candidates* binary and return its stdout."""
    for exe in candidates:
        binary = shutil.which(exe)
        if binary is None:
            continue
        try:
            out = subprocess.run(
                [binary, *args], capture_output=True, text=True, timeout=30
            )
        except (OSError, subprocess.TimeoutExpired):
            continue
        if out.returncode == 0 and out.stdout.strip():
            return out.stdout.strip()
    return None


def _pwsh_profiles() -> list[Path]:
    """Every distinct `$PROFILE` among the PowerShells on PATH.

    PowerShell 7 (`pwsh`) and Windows PowerShell (`powershell`) keep
    *different* profile files; on a machine with both, completion should work
    in whichever one the user opens — so the installer targets them all.
    """
    profiles: list[Path] = []
    for exe in ("pwsh", "powershell"):
        path = _ask_shell((exe,), ["-NoProfile", "-Command", "$PROFILE"])
        if path is not None and Path(path) not in profiles:
            profiles.append(Path(path))
    if not profiles:
        raise InstallError(
            "pwsh (or powershell) not found on PATH — install PowerShell first"
        )
    return profiles


def _nu_config_path() -> Path:
    """The config file nushell itself reports (`$nu.config-path`)."""
    path = _ask_shell(("nu",), ["-c", "$nu.config-path"])
    if path is None:
        raise InstallError("nu not found on PATH — install nushell first")
    return Path(path)


def _bash_path(path: Path | str, *, windows: bool | None = None) -> str:
    """*path* as the bash on this platform can read it.

    A Windows path is unusable inside a bash rc: backslashes are escapes,
    so `source C:\\Users\\me\\...` silently sources nothing. git-bash
    understands the MSYS spelling — `/c/Users/me/...` — which is what this
    produces; elsewhere the path is already right.

    *windows* is explicit so the translation can be tested from any
    platform: string surgery only, because building a Windows `Path` on a
    POSIX box is impossible and monkeypatching `os.name` to pretend
    otherwise breaks pathlib for everything else in the process.
    """
    if windows is None:
        windows = os.name == "nt"
    text = str(path)
    if not windows:
        return text
    text = text.replace("\\", "/")
    drive, colon, rest = text.partition(":")
    if colon and len(drive) == 1:
        return f"/{drive.lower()}{rest}"
    return text


def install(shell: str, prog: str) -> list[str]:
    """Install completion for *shell*; return the lines to tell the user.

    Raises `KeyError` for an unsupported shell and `InstallError` when the
    shell itself is missing — the caller owns the taught error (it knows the
    brand).
    """
    script = script_for(shell, prog)

    if shell == "fish":
        target = _paths.config_home() / "fish" / "completions" / f"{prog}.fish"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(script, encoding="utf-8")
        return [
            f"installed {target}",
            "fish picks it up automatically — start a new shell and TAB away.",
        ]

    target = hook_path(shell, prog)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(script, encoding="utf-8")
    if shell == "pwsh":
        # The hook runs on PowerShell 5+ unchanged, so it goes into every
        # PowerShell profile present — both shells complete, whoever answers.
        hooks = [(rc, f'. "{target}"') for rc in _pwsh_profiles()]
    elif shell == "nushell":
        hooks = [(_nu_config_path(), f'source "{target}"')]
    elif shell == "zsh":
        hooks = [(_zsh_rc(), f"source {_bash_path(target)}")]
    else:  # bash — git-bash included, hence the MSYS-spelled path
        hooks = [(rc, f"source {_bash_path(target)}") for rc in _bash_rcs()]
    lines = [f"installed {target}"]
    for rc, line in hooks:
        if _append_once(rc, line):
            lines.append(f"added `{line}` to {rc}")
        else:
            lines.append(f"{rc} already sources it")
    lines.append("restart your shell (or source the rc file) and TAB away.")
    return lines


def hook_path(shell: str, prog: str) -> Path:
    """Where *shell* keeps *prog*'s completion script.

    One spelling, because three copies of it is what the comment in
    `uninstall` used to warn about: install writing one path and uninstall
    computing another leaves the script removed and its rc line behind,
    sourcing nothing. fish owns its own conventional directory; everyone
    else gets `<data home>/<prog>/completion.<suffix>`.

    Note this is keyed by the **command name**, not the config stem, so it
    sits *beside* `data_dir()` rather than inside it — `~/.local/share/fm/`
    next to `~/.local/share/footman/`. Anything clearing a runner's
    leavings has to know that.
    """
    if shell == "fish":
        return _paths.config_home() / "fish" / "completions" / f"{prog}.fish"
    suffix = {"pwsh": "ps1", "nushell": "nu"}.get(shell, shell)
    return _paths.data_home() / prog / f"completion.{suffix}"


def uninstall(shell: str, prog: str) -> list[str]:
    """Remove *shell*'s completion for *prog*: the script file and the rc line.

    The mirror of `install()`, idempotent the same way — uninstalling what was
    never installed reports what it looked for rather than failing. When the
    shell itself is gone (its rc/profile can't be located any more), the
    script file is still removed and the leftover line is named, so finishing
    by hand is one paste.
    """
    if shell == "fish":
        target = hook_path(shell, prog)
        if target.exists():
            target.unlink()
            return [f"removed {target}"]
        return [f"nothing to remove ({target} was not installed)"]

    target = hook_path(shell, prog)
    hook = {
        "pwsh": f'. "{target}"',
        "nushell": f'source "{target}"',
    }.get(shell, f"source {_bash_path(target)}")

    lines: list[str] = []
    if target.exists():
        target.unlink()
        with contextlib.suppress(OSError):  # only when nothing else lives there
            target.parent.rmdir()
        lines.append(f"removed {target}")

    try:
        if shell == "pwsh":
            rcs = _pwsh_profiles()
        elif shell == "nushell":
            rcs = [_nu_config_path()]
        elif shell == "zsh":
            rcs = [_zsh_rc()]
        else:  # bash
            rcs = _bash_rcs()
    except InstallError as exc:
        lines.append(
            f"could not locate the rc file ({exc}) — "
            f"if it still sources the hook, remove this line yourself: {hook}"
        )
        return lines

    for rc in rcs:
        if _remove_once(rc, hook):
            lines.append(f"removed `{hook}` from {rc}")
    if not lines:
        lines.append(f"nothing to remove ({target} was not installed)")
    return lines
