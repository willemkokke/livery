"""Git access for the livery ecosystem, every call a function of the repository's root.

Reach for the named reader or mover first: [livery.git.position][]
for where a checkout stands, [livery.git.fetch][] and
[livery.git.push_force][] for the network, [livery.git.commit_all][]
for a commit. [livery.git.run][] and [livery.git.call][] are the door
for a subcommand no function names yet: `run` raises
[livery.git.GitError][] on a non-zero exit, `call` returns the result
whatever the code.

Nothing is held between calls, so a function may be called from any
process at any time and answers what git holds at that moment.
"""

