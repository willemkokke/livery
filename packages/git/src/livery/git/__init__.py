"""Git access for the livery ecosystem, every call a function of the repository's root.

Reach for the named reader or mover first: [livery.git.position][]
for where a checkout stands, [livery.git.fetch][] and
[livery.git.push_force][] for the network, [livery.git.commit_all][]
for a commit. [livery.git.run][] and [livery.git.call][] are the door
for a subcommand no function names yet: `run` raises
[livery.git.GitError][] on a non-zero exit, `call` returns the result
whatever the code.

Nothing is held between calls, so a function may be called from any
process at any time and answers what git holds at that moment.

The package is also a footman plugin, `plugin("livery.git")`: its hook
gives every task's git the ssh command that shares one connection per
host ([livery.git.ssh_environment][]), the tools' identity when the
person has none ([livery.git.tool_identity][]), an editor that never
opens, and what a task marks for itself with [livery.git.identity][]
and [livery.git.unsigned][].

The state store, JSON rows on git refs, is here too: a
[livery.git.StateStore][] built with a caller's policy, the
[livery.git.Series][] and [livery.git.Keyed][] declarations that read
and write through it, and the snapshots that make a run's reads one
listing and one fetch.
"""

